class Course:
    """Represents a course"""
    def __init__(self, course_id="", name="", credits=0):
        self.__id = course_id
        self.__name = name
        self.__credits = credits

    def get_id(self):
        return self.__id

    def get_name(self):
        return self.__name

    def get_credits(self):
        return self.__credits

    def __str__(self):
        return f"Course ID: {self.__id:<8} | Name: {self.__name:<20} | Credits: {self.__credits}"